"""Builds the app's icon font and lib/app/icons.dart from icons.txt.

Subsets Google's Material Symbols Outlined variable font to the listed
icons, keeping its FILL, GRAD, opsz and wght axes, so the APK carries a
few kilobytes of icons instead of the full 10 MB font (debug builds don't
tree-shake icons).

    python3 -m venv /tmp/ft && /tmp/ft/bin/pip install fonttools
    /tmp/ft/bin/python tool/icons/generate.py
"""
import os
import sys
import tempfile
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

# google/material-design-icons, pinned for reproducible output.
COMMIT = '49d4db35df873165d6bd6ba09b063c7dafbac2f4'
BASE = f'https://raw.githubusercontent.com/google/material-design-icons/{COMMIT}/variablefont/'
NAME = 'MaterialSymbolsOutlined%5BFILL,GRAD,opsz,wght%5D'

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT_OUT = os.path.join(ROOT, 'assets/fonts/MaterialSymbolsOutlined.ttf')
DART_OUT = os.path.join(ROOT, 'lib/app/icons.dart')


def fetch(name, into):
    path = os.path.join(into, name.replace('%5B', '[').replace('%5D', ']'))
    if not os.path.exists(path):
        urllib.request.urlretrieve(BASE + name, path)
    return path


def read_list():
    icons = []
    with open(os.path.join(ROOT, 'tool/icons/icons.txt')) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            entry, _, flag = line.partition(' ')
            dart, _, symbol = entry.partition('=')
            icons.append((dart, symbol or dart, flag == 'rtl'))
    return icons


def main():
    cache = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
    font = fetch(NAME + '.ttf', cache)
    codepoints = {}
    with open(fetch(NAME + '.codepoints', cache)) as f:
        for line in f:
            name, cp = line.split()
            codepoints[name] = int(cp, 16)
    icons = read_list()
    missing = [s for _, s, _ in icons if s not in codepoints]
    if missing:
        sys.exit(f'Not in Material Symbols: {", ".join(missing)}')

    options = subset.Options()
    options.layout_features = ['*']  # FILL swaps glyphs via feature variations
    options.notdef_outline = True
    options.name_IDs = ['*']
    options.drop_tables += ['DSIG']
    tt = TTFont(font)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted({codepoints[s] for _, s, _ in icons}))
    subsetter.subset(tt)
    tt.save(FONT_OUT)

    lines = [
        '// Generated by tool/icons/generate.py from tool/icons/icons.txt. Do not edit.',
        "import 'package:flutter/widgets.dart';",
        '',
        "/// The app's icons: Material Symbols Outlined, a variable font. Fill,",
        '/// weight, grade and optical size come from [IconTheme] or [Icon].',
        'abstract final class AppIcons {',
    ]
    for dart, symbol, rtl in sorted(icons):
        mirror = ', matchTextDirection: true' if rtl else ''
        lines.append(f"  static const {dart} = IconData(0x{codepoints[symbol]:x}, fontFamily: 'MaterialSymbols'{mirror});")
    lines.append('}')
    with open(DART_OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(icons)} icons, {os.path.getsize(FONT_OUT)} bytes')


if __name__ == '__main__':
    main()
